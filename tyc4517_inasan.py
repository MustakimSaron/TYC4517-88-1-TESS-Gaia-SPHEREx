def planck_lam_fl(lam_um, teff, r_rsun, dist_pc, av, k_av):
    lam_m = lam_um * 1e-6
    x = np.clip((H_PLANCK * C_LIGHT) / (lam_m * K_BOLTZ * teff), 1e-6, 700.0)
    b_lam = (2.0 * H_PLANCK * C_LIGHT ** 2 / (lam_m ** 5)) / np.expm1(x)
    return (
        lam_m * np.pi * b_lam
        * (r_rsun * R_SUN_M / (dist_pc * PC_M)) ** 2
        * np.power(10.0, -0.4 * av * k_av)
    )


def fetch_gaia_neighbors(radius_arcsec: float = 95.0) -> pd.DataFrame:
    """Fetch Gaia DR3 neighbors around TYC 4517-88-1 for finder chart overlay."""
    adql = f"""
    SELECT source_id, ra, dec, phot_g_mean_mag, phot_rp_mean_mag,
           DISTANCE(POINT('ICRS', ra, dec), POINT('ICRS', {TARGET_RA}, {TARGET_DEC})) * 3600.0 AS sep_arcsec
    FROM gaiadr3.gaia_source
    WHERE 1 = CONTAINS(POINT('ICRS', ra, dec), CIRCLE('ICRS', {TARGET_RA}, {TARGET_DEC}, {radius_arcsec / 3600.0}))
    ORDER BY sep_arcsec ASC
    """
    payload = {"REQUEST": "doQuery", "LANG": "ADQL", "FORMAT": "csv", "QUERY": adql.strip()}
    for url in GAIA_TAP_ENDPOINTS:
        try:
            r = requests.post(url, data=payload, timeout=45)
            r.raise_for_status()
            if not r.text.strip().startswith("<"):
                return pd.read_csv(io.StringIO(r.text))
        except Exception:
            continue
    return pd.DataFrame(columns=["source_id", "ra", "dec", "phot_g_mean_mag", "sep_arcsec"])


def fetch_wise_ir_cutout(fov_arcmin: float = 3.5, width_px: int = 420):
    """
    Fetch WCS-aligned WISE IR cutout:
      1. Legacy Survey Viewer full-sky unWISE W1/W2 color JPEG (unwise-neo7 / unwise-neo6)
      2. Failover: NASA SkyView WISE 3.4 um FITS image
    """
    headers = {"User-Agent": "Mozilla/5.0 (AstrophysicsPipeline/5.3)"}
    pixscale_arcsec = (fov_arcmin * 60.0) / width_px

    for layer in ("unwise-neo7", "unwise-neo6"):
        url = (
            f"https://www.legacysurvey.org/viewer/cutout.jpg"
            f"?ra={TARGET_RA:.6f}&dec={TARGET_DEC:.6f}"
            f"&layer={layer}&pixscale={pixscale_arcsec:.4f}&size={width_px}"
        )
        try:
            r = requests.get(url, headers=headers, timeout=45)
            r.raise_for_status()
            if "image" in r.headers.get("Content-Type", "").lower() and len(r.content) > 2000:
                img = plt.imread(io.BytesIO(r.content), format="jpg")
                img = np.flipud(img)
                w = WCS(naxis=2)
                w.wcs.crpix = [width_px / 2.0 + 0.5, width_px / 2.0 + 0.5]
                deg_per_px = pixscale_arcsec / 3600.0
                w.wcs.cdelt = [-deg_per_px, deg_per_px]
                w.wcs.crval = [TARGET_RA, TARGET_DEC]
                w.wcs.ctype = ["RA---TAN", "DEC--TAN"]
                print(f"[OK] Downloaded Legacy Survey {layer} IR color cutout ({img.shape})")
                return img, w, True, "unWISE W1/W2 Color"
        except Exception as exc:
            print(f"[WARN] Legacy Survey {layer} failed: {exc}")

    skyview_url = "https://skyview.gsfc.nasa.gov/current/cgi/runquery.pl"
    params = {
        "Position": f"{TARGET_RA:.6f},{TARGET_DEC:.6f}",
        "Survey": "WISE 3.4",
        "Pixels": "300",
        "Size": f"{fov_arcmin / 60.0:.6f}",
        "Return": "FITS",
    }
    print("[INFO] Falling back to NASA SkyView WISE 3.4 um FITS...")
    r = requests.get(skyview_url, params=params, headers=headers, timeout=60)
    r.raise_for_status()
    with fits.open(io.BytesIO(r.content)) as hdul:
        data = np.asarray(hdul[0].data, dtype=np.float64)
        w = WCS(hdul[0].header)
    print(f"[OK] Downloaded NASA SkyView WISE 3.4 um FITS ({data.shape})")
    return data, w, False, "AllWISE W1 (3.4 $\\mu$m)"


def extract_urls_from_votable_text(xml_text: str):
    """Extract all unique http/https URLs from VOTable XML (unescaping &amp;)."""
    unescaped = html.unescape(xml_text)
    raw_urls = re.findall(r"https?://[^\s<>\"']+", unescaped)
    data_urls = []
    for u_str in raw_urls:
        low = u_str.lower()
        if any(skip in low for skip in ("w3.org", "ivoa.net/xml", "xmlns", "schema")):
            continue
        if u_str not in data_urls:
            data_urls.append(u_str)
    return data_urls


def resolve_spherex_fits_url(sia_xml: str, headers: dict) -> str:
    """Locate the direct SPHEREx DR1 FITS cube URL from an IRSA SIA2 VOTable response."""
    candidate_urls = []
    try:
        tbl = parse_single_table(io.BytesIO(sia_xml.encode("utf-8"))).to_table()
        for col in tbl.colnames:
            for val in tbl[col]:
                s = val.decode("utf-8", errors="ignore") if isinstance(val, (bytes, bytearray)) else str(val)
                s = s.strip()
                if s.startswith("http://") or s.startswith("https://"):
                    if s not in candidate_urls:
                        candidate_urls.append(s)
    except Exception:
        pass

    for u_str in extract_urls_from_votable_text(sia_xml):
        if u_str not in candidate_urls:
            candidate_urls.append(u_str)

    if not candidate_urls:
        raise RuntimeError(f"No data URLs found in IRSA SIA2 response. Snippet:\n{sia_xml[:600]}")

    direct_fits = [u for u in candidate_urls if ".fits" in u.lower() and "datalink" not in u.lower()]
    if direct_fits:
        cube_fits = [u for u in direct_fits if "hips5_cube" in u.lower() or "cube" in u.lower()]
        return cube_fits[0] if cube_fits else direct_fits[0]

    dl_urls = [u for u in candidate_urls if "datalink" in u.lower() or "irsa.ipac.caltech.edu" in u.lower()]
    for dl in dl_urls:
        r_dl = requests.get(dl, headers=headers, timeout=60)
        r_dl.raise_for_status()
        if r_dl.content[:8] == b"SIMPLE  ":
            return dl
        inner_urls = extract_urls_from_votable_text(r_dl.text)
        inner_fits = [u for u in inner_urls if ".fits" in u.lower() and "datalink" not in u.lower()]
        if inner_fits:
            cube_fits = [u for u in inner_fits if "hips5_cube" in u.lower() or "cube" in u.lower()]
            return cube_fits[0] if cube_fits else inner_fits[0]

    raise RuntimeError(f"Could not resolve a direct .fits URL from candidates: {candidate_urls[:5]}")


def download_spherex_dr1_cube(cache_path: str = "spherex_dr1_tile_tic397073349.fits") -> str:
    """Query IRSA SIA2 for the SPHEREx DR1 All-Sky Cube tile covering TYC 4517-88-1."""
    if os.path.exists(cache_path) and os.path.getsize(cache_path) > 10_000_000:
        with open(cache_path, "rb") as fh:
            if fh.read(8) == b"SIMPLE  ":
                print(f"[OK] Using cached SPHEREx DR1 All-Sky Cube: {cache_path}")
                return cache_path

    params = {
        "COLLECTION": "spherex_dr1_cube",
        "POS": f"circle {TARGET_RA:.6f} {TARGET_DEC:.6f} 0.01",
    }
    headers = {"User-Agent": "Mozilla/5.0 (AstrophysicsPipeline/5.3)"}
    print("[INFO] Querying IRSA SIA2 for SPHEREx DR1 All-Sky Cube (DOI: 10.26131/IRSA679)...")
    r = requests.get(SPHEREX_SIA_URL, params=params, headers=headers, timeout=60)
    r.raise_for_status()

    cube_url = resolve_spherex_fits_url(r.text, headers)
    print(f"[INFO] Streaming SPHEREx DR1 FITS Cube:\n       {cube_url}")

    with requests.get(cube_url, headers=headers, stream=True, timeout=300) as resp:
        resp.raise_for_status()
        total = int(resp.headers.get("content-length", 0))
        downloaded = 0
        first_chunk = True
        with open(cache_path, "wb") as fh:
            for chunk in resp.iter_content(chunk_size=1024 * 1024):
                if chunk:
                    if first_chunk:
                        if not chunk.startswith(b"SIMPLE  "):
                            raise RuntimeError(f"Stream is not a FITS file: {chunk[:200]!r}")
                        first_chunk = False
                    fh.write(chunk)
                    downloaded += len(chunk)
        print(f"[OK] Downloaded {downloaded / 1e6:.1f} MB (expected {total / 1e6:.1f} MB) -> {cache_path}")
    return cache_path


def extract_spherex_cube_spectrum_and_cutout(cube_path: str):
    """Extract 100-channel aperture-photometry spectrum and 1.3-2.2 um cutout from SPHEREx DR1 cube."""
    with fits.open(cube_path, memmap=True) as hdul:
        img_hdu = hdul["IMAGE"] if "IMAGE" in hdul else hdul[0]
        hdr = img_hdu.header
        cube = img_hdu.data
        nhits = hdul["NHITS"].data if "NHITS" in hdul else None
        blank_str = str(hdr.get("BLANKCH", ""))

        wcs_3d = WCS(hdr, fobj=hdul)
        wcs_cel = wcs_3d.celestial

        coord = SkyCoord(ra=TARGET_RA * u.deg, dec=TARGET_DEC * u.deg, frame="icrs")
        x_t, y_t = wcs_cel.world_to_pixel(coord)
        x_t, y_t = float(x_t), float(y_t)
        n_ch, ny, nx = cube.shape

        pix_area_deg2 = float(proj_plane_pixel_area(wcs_cel))
        pix_area_arcsec2 = pix_area_deg2 * (3600.0 ** 2)
        pix_scale_arcsec = np.sqrt(pix_area_arcsec2)

        ch_idx = np.arange(n_ch, dtype=float)
        try:
            spec_world = wcs_3d.spectral.pixel_to_world(ch_idx)
            lam_um = spec_world.to(u.um).value
        except Exception:
            lam_um = None
            for h in hdul:
                if h.is_image is False and h.data is not None:
                    for col in h.columns.names:
                        arr = np.asarray(h.data[col]).ravel()
                        if len(arr) == n_ch and np.nanmax(arr) < 1e-4:
                            lam_um = arr * 1e6
                            break
                        if len(arr) == n_ch and 0.5 < np.nanmin(arr) and np.nanmax(arr) < 6.0:
                            lam_um = arr
                            break
            if lam_um is None:
                raise RuntimeError("Could not extract wavelength array from SPHEREx DR1 cube.")

        half = 12
        ix0, iy0 = int(round(x_t)), int(round(y_t))
        x_lo, x_hi = max(0, ix0 - half), min(nx, ix0 + half + 1)
        y_lo, y_hi = max(0, iy0 - half), min(ny, iy0 + half + 1)

        stamp = np.asarray(cube[:, y_lo:y_hi, x_lo:x_hi], dtype=np.float64)
        nh_stamp = np.asarray(nhits[:, y_lo:y_hi, x_lo:x_hi], dtype=np.float64) if nhits is not None else None

        yy, xx = np.mgrid[y_lo:y_hi, x_lo:x_hi]
        rr = np.hypot(xx - x_t, yy - y_t)

        ap_mask = rr <= 2.0
        sky_mask = (rr >= 3.5) & (rr <= 6.5)
        n_ap = int(np.sum(ap_mask))

        blank_set = {int(tok) for tok in blank_str.replace(",", " ").split() if tok.isdigit()}

        spec_rows = []
        for k in range(n_ch):
            ch_1based = k + 1
            if ch_1based in blank_set:
                continue
            plane = stamp[k]
            ap_vals = plane[ap_mask]
            sky_vals = plane[sky_mask]
            good_ap = np.isfinite(ap_vals)
            good_sky = np.isfinite(sky_vals)
            if np.sum(good_ap) < max(5, int(0.75 * n_ap)) or np.sum(good_sky) < 15:
                continue

            if nh_stamp is not None:
                nh_center = nh_stamp[k, iy0 - y_lo, ix0 - x_lo]
                if not np.isfinite(nh_center) or nh_center <= 0:
                    continue

            sky_med = float(np.nanmedian(sky_vals[good_sky]))
            sky_mad = 1.4826 * float(np.nanmedian(np.abs(sky_vals[good_sky] - sky_med)))
            sky_clean = sky_vals[good_sky]
            if sky_mad > 0:
                sky_clean = sky_clean[np.abs(sky_clean - sky_med) < 3.0 * sky_mad]
            if len(sky_clean) < 10:
                continue
            sky_bg = float(np.median(sky_clean))
            sky_std = 1.4826 * float(np.median(np.abs(sky_clean - sky_bg)))

            net_sum_mjysr = float(np.sum(ap_vals[good_ap] - sky_bg))
            if np.sum(good_ap) < n_ap:
                net_sum_mjysr *= (n_ap / np.sum(good_ap))

            fnu_jy = net_sum_mjysr * JY_PER_MJYSR_ARCSEC2 * pix_area_arcsec2
            err_sum_mjysr = sky_std * np.sqrt(n_ap * (1.0 + n_ap / len(sky_clean)))
            fnu_err_jy = err_sum_mjysr * JY_PER_MJYSR_ARCSEC2 * pix_area_arcsec2

            if fnu_jy <= 0:
                continue

            lam_val = float(lam_um[k])
            nu_hz = C_LIGHT / (lam_val * 1e-6)
            lam_fl = nu_hz * fnu_jy * 1e-26
            lam_fl_err = nu_hz * fnu_err_jy * 1e-26

            spec_rows.append({
                "channel": ch_1based,
                "lam_um": lam_val,
                "fnu_mjy": fnu_jy * 1e3,
                "fnu_err_mjy": fnu_err_jy * 1e3,
                "lam_Fl_wm2": lam_fl,
                "lam_Fl_err": lam_fl_err,
                "snr": fnu_jy / max(fnu_err_jy, 1e-12),
            })

        spec_df = pd.DataFrame(spec_rows).sort_values("lam_um").reset_index(drop=True)
        b23_mask = (lam_um >= 1.30) & (lam_um <= 2.20)
        b23_img = np.nanmedian(stamp[b23_mask], axis=0)
        wcs_stamp = wcs_cel.slice((slice(y_lo, y_hi), slice(x_lo, x_hi)))

    return spec_df, b23_img, wcs_stamp, pix_scale_arcsec


