def planck_lam_fl(lam_um, teff, r_rsun, dist_pc, av, k_av):
    """Reddened blackbody lambda*F_lambda (W m^-2) at Earth."""
    lam_m = lam_um * 1e-6
    x = np.clip((H_PLANCK * C_LIGHT) / (lam_m * K_BOLTZ * teff), 1e-6, 700.0)
    b_lam = (2.0 * H_PLANCK * C_LIGHT ** 2 / (lam_m ** 5)) / np.expm1(x)
    ang_factor = (r_rsun * R_SUN_M / (dist_pc * PC_M)) ** 2
    ext_factor = np.power(10.0, -0.4 * av * k_av)
    return lam_m * np.pi * b_lam * ang_factor * ext_factor


def fit_sed_single_and_binary(sed: pd.DataFrame, dist_pc: float, av_prior: float):
    """Fit single-star and two-component blackbody SEDs."""
    lam = sed["lam_um"].values
    k_av = sed["k_av"].values
    y_obs = sed["lam_Fl_wm2"].values
    y_err = sed["lam_Fl_err"].values

    def res_single(p):
        teff, r_eff, av = p
        y_mod = planck_lam_fl(lam, teff, r_eff, dist_pc, av, k_av)
        r_phot = (y_obs - y_mod) / y_err
        if np.isfinite(av_prior):
            return np.append(r_phot, (av - av_prior) / 0.15)
        return r_phot

    p0 = [6500.0, 2.2, av_prior if np.isfinite(av_prior) else 0.35]
    lsq1 = least_squares(res_single, x0=p0, bounds=([4500.0, 0.5, 0.0], [9500.0, 8.0, 1.5]))
    teff1, r1_sed, av1 = lsq1.x
    dof1 = max(len(lam) - 3, 1)
    y_mod1 = planck_lam_fl(lam, teff1, r1_sed, dist_pc, av1, k_av)
    chi2_1 = float(np.sum(((y_obs - y_mod1) / y_err) ** 2))
    cov1 = (chi2_1 / dof1) * np.linalg.pinv(lsq1.jac.T @ lsq1.jac)
    err1 = np.sqrt(np.maximum(np.diag(cov1), 0.0))

    def res_binary(p):
        t1, r1, t2, r2, av = p
        y_mod = (
            planck_lam_fl(lam, t1, r1, dist_pc, av, k_av)
            + planck_lam_fl(lam, t2, r2, dist_pc, av, k_av)
        )
        r_phot = (y_obs - y_mod) / y_err
        if np.isfinite(av_prior):
            return np.append(r_phot, (av - av_prior) / 0.15)
        return r_phot

    lsq2 = least_squares(
        res_binary,
        x0=[6600.0, 1.9, 5500.0, 1.2, av1],
        bounds=([5500.0, 0.8, 3200.0, 0.2, 0.0], [8500.0, 5.0, 7500.0, 3.5, 1.5]),
    )
    y_mod2 = (
        planck_lam_fl(lam, lsq2.x[0], lsq2.x[1], dist_pc, lsq2.x[4], k_av)
        + planck_lam_fl(lam, lsq2.x[2], lsq2.x[3], dist_pc, lsq2.x[4], k_av)
    )
    chi2_2 = float(np.sum(((y_obs - y_mod2) / y_err) ** 2))

    return {
        "teff1": teff1, "teff1_err": err1[0],
        "r_eff": r1_sed, "r_eff_err": err1[1],
        "av": av1, "av_err": err1[2],
        "chi2_1": chi2_1, "dof1": dof1, "y_mod1": y_mod1,
        "bin_params": lsq2.x, "chi2_2": chi2_2, "y_mod2": y_mod2,
    }


def solve_kepler_and_epochs(p_orb, t_peri_gaia, ecc, omega_deg, t_ref_btjd):
    """
    Gaia DR3 nss_two_body_orbit reference epoch is BJD 2457389.0 (J2016.0 TCB).
    TESS BTJD = BJD - 2457000.0  =>  T_peri_BTJD = t_peri_gaia + 389.0.
    """
    t_peri_btjd = t_peri_gaia + 389.0
    n_cyc = round((t_ref_btjd - t_peri_btjd) / p_orb)
    t_peri_mid = t_peri_btjd + n_cyc * p_orb
    omega = np.radians(omega_deg)

    def nu_to_phase(nu_rad):
        e_anom = 2.0 * np.arctan2(
            np.sqrt(1.0 - ecc) * np.sin(nu_rad / 2.0),
            np.sqrt(1.0 + ecc) * np.cos(nu_rad / 2.0),
        )
        m_anom = (e_anom - ecc * np.sin(e_anom)) % (2.0 * np.pi)
        return float(m_anom / (2.0 * np.pi))

    return {
        "t_peri_btjd_orig": t_peri_btjd,
        "t_peri_btjd_mid": t_peri_mid,
        "n_cyc_from_gaia": n_cyc,
        "phi_rv_recede": nu_to_phase(0.0 - omega),
        "phi_rv_approach": nu_to_phase(np.pi - omega),
        "phi_conj_sup": nu_to_phase(0.5 * np.pi - omega),
        "phi_conj_inf": nu_to_phase(1.5 * np.pi - omega),
    }


def solve_m2_from_fm(fm, m1, inc_deg):
    """Solve m2^3 * sin^3(i) / (m1 + m2)^2 = fm."""
    sini = np.sin(np.radians(inc_deg))
    if sini <= 1e-4:
        return np.nan
    roots = np.roots([sini ** 3, -fm, -2.0 * fm * m1, -fm * m1 ** 2])
    real_pos = [np.real(r) for r in roots if abs(np.imag(r)) < 1e-8 and np.real(r) > 0]
    return float(min(real_pos)) if real_pos else np.nan


def doppler_beaming_alpha(teff, lam_um=0.7865):
    """Blackbody Doppler beaming factor x * exp(x) / (exp(x) - 1)."""
    x = (H_PLANCK * C_LIGHT) / (lam_um * 1e-6 * K_BOLTZ * teff)
    return float(x * np.exp(x) / np.expm1(x))


