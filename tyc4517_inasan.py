def query_vizier_catalog(catalog: str, ra: float, dec: float, radius_arcsec: float = 5.0):
    """Query a VizieR catalog via ASU TSV with CfA/CDS failover."""
    params = {
        "-source": catalog,
        "-c": f"{ra:.6f} {dec:+.6f}",
        "-c.rs": f"{radius_arcsec:.1f}",
        "-out.max": "5",
        "-out.all": "1",
    }
    headers = {"User-Agent": "Mozilla/5.0 (AstrophysicsPipeline/3.0)"}
    for name, url in VIZIER_ASU_ENDPOINTS:
        try:
            r = requests.get(url, params=params, headers=headers, timeout=30)
            r.raise_for_status()
            lines = [ln for ln in r.text.splitlines() if ln and not ln.startswith("#")]
            # VizieR TSV has header, units, dashed line, then data rows
            if len(lines) >= 4:
                header = lines[0].split("\t")
                # Data starts after dashed separator line
                sep_idx = next((i for i, ln in enumerate(lines) if ln.startswith("---")), 2)
                data_lines = lines[sep_idx + 1:]
                if data_lines:
                    rows = [ln.split("\t") for ln in data_lines]
                    return pd.DataFrame(rows, columns=header)
            return pd.DataFrame()
        except Exception:
            continue
    return pd.DataFrame()


def fetch_all_tess_sectors(tic_id: int):
    """Download ALL unique TESS sectors for TIC 397073349 using highest-priority pipeline per sector."""
    sr = lk.search_lightcurve(f"TIC {tic_id}", mission="TESS")
    if sr is None or len(sr) == 0:
        raise RuntimeError(f"No TESS light curves found for TIC {tic_id}")

    tbl = sr.table
    print(f"\n[INFO] Total MAST light-curve entries found for TIC {tic_id}: {len(tbl)}")

    sector_best = {}
    for i in range(len(tbl)):
        author = str(tbl["author"][i]).upper()
        if author not in PIPELINE_PRIORITY:
            continue
        mission_str = str(tbl["mission"][i])
        prio = PIPELINE_PRIORITY[author]
        exptime = float(tbl["exptime"][i]) if "exptime" in tbl.colnames else 1800.0
        rank = (prio, exptime)
        if mission_str not in sector_best or rank < sector_best[mission_str][0]:
            sector_best[mission_str] = (rank, i, author, exptime)

    # Sort sectors numerically by sector number
    def sec_num(m_str):
        digits = "".join(ch for ch in m_str if ch.isdigit())
        return int(digits) if digits else 999

    selected = sorted(sector_best.items(), key=lambda kv: sec_num(kv[0]))
    print(f"[INFO] Unique TESS sectors available: {len(selected)}")

    sectors_data = []
    for sec_name, (_, idx, author, exptime) in selected:
        try:
            lc = sr[idx].download()
            if lc is None:
                continue
            meta = lc.meta if hasattr(lc, "meta") else {}
            crowdsap = meta.get("CROWDSAP", np.nan)
            flfrcsap = meta.get("FLFRCSAP", np.nan)
            sec_id = meta.get("SECTOR", sec_num(sec_name))

            lc = lc.remove_nans()
            t = np.asarray(lc.time.value, dtype=float)
            f = np.asarray(lc.flux.value, dtype=float)
            if lc.flux_err is not None and np.all(np.isfinite(lc.flux_err.value)):
                e = np.asarray(lc.flux_err.value, dtype=float)
            else:
                e = np.full_like(f, np.nanstd(f))

            good = np.isfinite(t) & np.isfinite(f) & (f > 0)
            t, f, e = t[good], f[good], e[good]
            if len(t) < 50:
                continue

            med = np.nanmedian(f)
            f_norm = f / med - 1.0
            e_norm = e / med

            # Sigma-clip outliers (> 5 sigma MAD)
            mad = 1.4826 * np.nanmedian(np.abs(f_norm))
            if mad > 0:
                keep = np.abs(f_norm) < 5.0 * mad
                t, f_norm, e_norm = t[keep], f_norm[keep], e_norm[keep]

            # Remove slow per-sector polynomial drift (degree 2, timescale >> 2.63 d)
            t_c = t - np.mean(t)
            coef = np.polyfit(t_c, f_norm, 2)
            f_detr = f_norm - np.polyval(coef, t_c)

            sectors_data.append({
                "sector": int(sec_id),
                "author": author,
                "exptime_s": float(exptime),
                "crowdsap": float(crowdsap) if crowdsap is not None else np.nan,
                "flfrcsap": float(flfrcsap) if flfrcsap is not None else np.nan,
                "t": t,
                "f": f_detr,
                "e": e_norm,
                "t_mid": float(np.mean(t)),
                "npts": len(t),
            })
            print(
                f"  -> Sector {int(sec_id):2d} | {author:<9} | exp={exptime:6.0f}s | "
                f"N={len(t):5d} | CROWDSAP={crowdsap} | t_mid={np.mean(t):.1f}"
            )
        except Exception as exc:
            print(f"  -> Sector {sec_name} FAILED: {exc}")

    return sectors_data


def fit_harmonics_linear(t, f, f_orb, t0_ref, n_harm=4):
    """
    Fit f(t) = c0 + sum_{k=1..n_harm} [ a_k cos(2 pi k f_orb (t-t0)) + b_k sin(2 pi k f_orb (t-t0)) ]
    Returns amplitudes, phases, parameter uncertainties, and model curve.
    """
    dt = t - t0_ref
    cols = [np.ones_like(dt)]
    for k in range(1, n_harm + 1):
        ang = 2.0 * np.pi * k * f_orb * dt
        cols.append(np.cos(ang))
        cols.append(np.sin(ang))
    X = np.column_stack(cols)
    beta, _, _, _ = np.linalg.lstsq(X, f, rcond=None)
    resid = f - X @ beta
    dof = max(len(t) - X.shape[1], 1)
    s2 = np.sum(resid ** 2) / dof
    cov = s2 * np.linalg.pinv(X.T @ X)
    errs = np.sqrt(np.maximum(np.diag(cov), 0.0))

    out = {"c0": beta[0], "rms_ppm": 1e6 * np.std(resid), "model": X @ beta, "resid": resid}
    for k in range(1, n_harm + 1):
        ak, bk = beta[2 * k - 1], beta[2 * k]
        sak, sbk = errs[2 * k - 1], errs[2 * k]
        amp = np.hypot(ak, bk)
        # Error propagation on amplitude
        amp_err = np.sqrt((ak * sak) ** 2 + (bk * sbk) ** 2) / max(amp, 1e-12)
        # Phase of maximum: a cos(x) + b sin(x) = A cos(x - phi_max), phi_max = atan2(b, a)
        phi_rad = np.arctan2(bk, ak) % (2.0 * np.pi)
        phi_cyc = phi_rad / (2.0 * np.pi)
        out[f"A{k}_ppm"] = 1e6 * amp
        out[f"A{k}_err_ppm"] = 1e6 * amp_err
        out[f"a{k}_ppm"] = 1e6 * ak
        out[f"b{k}_ppm"] = 1e6 * bk
        out[f"phi{k}_cyc"] = phi_cyc
    return out


def refine_orbital_period(t, f, p_init, t0_ref):
    """Non-linear least-squares refinement of orbital period using 3-harmonic model."""
    def residuals(params):
        p = params[0]
        f_orb = 1.0 / p
        dt = t - t0_ref
        cols = [np.ones_like(dt)]
        for k in (1, 2, 3):
            ang = 2.0 * np.pi * k * f_orb * dt
            cols.append(np.cos(ang))
            cols.append(np.sin(ang))
        X = np.column_stack(cols)
        beta, _, _, _ = np.linalg.lstsq(X, f, rcond=None)
        return f - X @ beta

    # Coarse grid search around p_init +/- 0.005 d to avoid local alias minima
    p_grid = np.linspace(p_init - 0.004, p_init + 0.004, 1601)
    rss = np.empty_like(p_grid)
    for i, pg in enumerate(p_grid):
        r = residuals([pg])
        rss[i] = np.dot(r, r)
    p_best_coarse = float(p_grid[int(np.argmin(rss))])

    res = least_squares(residuals, x0=[p_best_coarse], bounds=([p_best_coarse - 0.001], [p_best_coarse + 0.001]))
    p_opt = float(res.x[0])
    # Formal 1-sigma uncertainty from Jacobian
    dof = max(len(t) - 8, 1)
    s2 = np.sum(res.fun ** 2) / dof
    jtj = res.jac.T @ res.jac
    p_err = float(np.sqrt(s2 / max(jtj[0, 0], 1e-30)))
    return p_opt, p_err


def rv_phase_at_btjd(t_btjd, p_orb, t_peri_gaia, e, omega_deg):
    """
    Convert Gaia DR3 t_periastron (BJD - 2457388.5, i.e., J2016.0 = BJD 2457388.5)
    to TESS BTJD (BJD - 2457000.0):
      T_peri_BTJD = t_peri_gaia + 388.5
    Solve Kepler's equation and compute normalized radial velocity RV(t) ~ cos(nu + omega) + e cos(omega).
    Also returns conjunction epoch T_conj_BTJD where primary is closest to observer (nu + omega = 3*pi/2).
    """
    t_peri_btjd = t_peri_gaia + 388.5
    omega = np.radians(omega_deg)
    M = 2.0 * np.pi * ((t_btjd - t_peri_btjd) / p_orb) % (2.0 * np.pi)
    E = M.copy()
    for _ in range(12):
        E = E - (E - e * np.sin(E) - M) / (1.0 - e * np.cos(E))
    nu = 2.0 * np.arctan2(np.sqrt(1.0 + e) * np.sin(E / 2.0), np.sqrt(1.0 - e) * np.cos(E / 2.0))
    rv_unit = np.cos(nu + omega) + e * np.cos(omega)
    return rv_unit, nu


