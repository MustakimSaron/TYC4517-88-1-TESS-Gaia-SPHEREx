def fast_lombscargle_amp_ppm(t: np.ndarray, y: np.ndarray, freqs: np.ndarray) -> np.ndarray:
    """
    Memory-safe Lomb-Scargle amplitude spectrum in ppm.
    Uses O(N log N) Press & Rybicki FFT via astropy (peak RAM <20 MB),
    with a strictly chunked pure-NumPy fallback if astropy is unavailable.
    """
    y0 = np.asarray(y, dtype=np.float64) - float(np.mean(y))
    t0 = np.asarray(t, dtype=np.float64)
    var_y = float(np.var(y0))
    if var_y <= 0.0:
        return np.zeros_like(freqs, dtype=np.float64)

    if HAS_ASTROPY_LS:
        ls = AstropyLS(t0, y0, center_data=True, fit_mean=True, normalization="standard")
        power = ls.power(freqs, method="fast", assume_regular_frequency=True)
        power = np.clip(np.asarray(power, dtype=np.float64), 0.0, 1.0)
        return 1e6 * np.sqrt(2.0 * power * var_y)

    # Strictly chunked pure-NumPy GLS fallback (chunk_size=128 -> <45 MB RAM)
    chunk_size = 128
    yy = float(np.dot(y0, y0))
    power = np.empty(len(freqs), dtype=np.float64)
    for start in range(0, len(freqs), chunk_size):
        end = min(start + chunk_size, len(freqs))
        w = 2.0 * np.pi * freqs[start:end]
        ang = np.outer(t0, w)  # shape (N, <=128)
        c = np.cos(ang)
        s = np.sin(ang)
        yc = y0 @ c
        ys = y0 @ s
        cc = np.sum(c * c, axis=0)
        ss = np.sum(s * s, axis=0)
        cs = np.sum(c * s, axis=0)
        det = np.maximum(cc * ss - cs * cs, 1e-18)
        p_chunk = (ss * yc * yc + cc * ys * ys - 2.0 * cs * yc * ys) / (det * yy)
        power[start:end] = np.clip(p_chunk, 0.0, 1.0)
        del ang, c, s
    return 1e6 * np.sqrt(2.0 * power * var_y)


def run_tap_csv(endpoints, query: str, timeout: int = 90) -> pd.DataFrame:
    payload = {"REQUEST": "doQuery", "LANG": "ADQL", "FORMAT": "csv", "QUERY": query.strip()}
    headers = {"User-Agent": "Mozilla/5.0 (AstrophysicsPipeline/4.1)"}
    last_err = None
    for _, url in endpoints:
        try:
            r = requests.post(url, data=payload, headers=headers, timeout=timeout)
            r.raise_for_status()
            txt = r.text.strip()
            if not txt or txt.startswith("<?xml") or txt.startswith("<html"):
                raise RuntimeError(f"Non-CSV response: {txt[:200]}")
            return pd.read_csv(io.StringIO(txt))
        except Exception as exc:
            last_err = exc
    raise RuntimeError(f"All TAP endpoints failed: {last_err}")


def query_vizier_catalog(catalog: str, ra: float, dec: float, radius_arcsec: float = 6.0) -> pd.DataFrame:
    params = {
        "-source": catalog,
        "-c": f"{ra:.6f} {dec:+.6f}",
        "-c.rs": f"{radius_arcsec:.1f}",
        "-out.max": "5",
        "-out.all": "1",
    }
    headers = {"User-Agent": "Mozilla/5.0 (AstrophysicsPipeline/4.1)"}
    for _, url in VIZIER_ASU_ENDPOINTS:
        try:
            r = requests.get(url, params=params, headers=headers, timeout=30)
            r.raise_for_status()
            lines = [ln for ln in r.text.splitlines() if ln and not ln.startswith("#")]
            if len(lines) >= 4:
                header = lines[0].split("\t")
                sep_idx = next((i for i, ln in enumerate(lines) if ln.startswith("---")), 2)
                data_lines = lines[sep_idx + 1:]
                if data_lines:
                    rows = [ln.split("\t") for ln in data_lines]
                    return pd.DataFrame(rows, columns=header)
            return pd.DataFrame()
        except Exception:
            continue
    return pd.DataFrame()


