C_LIGHT = 2.99792458e8
K_BOLTZ = 1.380649e-23
R_SUN_M = 6.957e8
PC_M = 3.085677581e16


def planck_lam_fl(lam_um, teff, r_rsun, dist_pc, av, k_av):
    lam_m = lam_um * 1e-6
    x = np.clip((H_PLANCK * C_LIGHT) / (lam_m * K_BOLTZ * teff), 1e-6, 700.0)
    b_lam = (2.0 * H_PLANCK * C_LIGHT ** 2 / (lam_m ** 5)) / np.expm1(x)
    return lam_m * np.pi * b_lam * (r_rsun * R_SUN_M / (dist_pc * PC_M)) ** 2 * np.power(10.0, -0.4 * av * k_av)


def solve_m2(fm, m1, inc_deg):
    sini = np.sin(np.radians(inc_deg))
    roots = np.roots([sini ** 3, -fm, -2.0 * fm * m1, -fm * m1 ** 2])
    pos = [np.real(r) for r in roots if abs(np.imag(r)) < 1e-8 and np.real(r) > 0]
    return float(min(pos)) if pos else np.nan


def solve_epochs():
    t_peri_btjd = TP_GAIA + 389.0
    tess = pd.read_csv("tic397073349_all_tess.csv")
    t_mid = float(tess["btjd"].mean())
    n_cyc = round((t_mid - t_peri_btjd) / P_TESS)
    t0_peri = t_peri_btjd + n_cyc * P_TESS
    omega = np.radians(OMEGA_DEG)

    def nu_to_phase(nu_rad):
        ea = 2.0 * np.arctan2(np.sqrt(1 - ECC) * np.sin(nu_rad / 2), np.sqrt(1 + ECC) * np.cos(nu_rad / 2))
        return float(((ea - ECC * np.sin(ea)) % (2 * np.pi)) / (2 * np.pi))

    return tess, t0_peri, nu_to_phase(0.0 - omega), nu_to_phase(np.pi - omega)


